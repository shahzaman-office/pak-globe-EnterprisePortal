do $$
declare t text;
begin
  foreach t in array array['branches','users','hotels','hotel_vendors','vendors','queries','quotations','transport','recycle_bin','quotation_packages'] loop
    execute format('drop trigger if exists trg_%I_updated_at on public.%I', t, t);
    execute format('create trigger trg_%I_updated_at before update on public.%I for each row execute function public.set_updated_at()', t, t);
  end loop;
end $$;

-- Keep all data behind the Express API. The service-role key bypasses RLS on the server.
do $$ declare t text; begin
  foreach t in array array['branches','users','hotels','hotel_vendors','vendors','settings','queries','quotations','transport','hotels_master','images','audit_logs','recycle_bin','backups','quotation_packages','package_payments','scheduled_emails'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists service_role_all on public.%I', t);
    execute format('create policy service_role_all on public.%I for all to service_role using (true) with check (true)', t);
  end loop;
end $$;

