  checkin_date date, checkout_date date, guest_names text, notes text,
  status text not null default 'new' check (status in ('new','checking_rates','checking_avail','confirm_whatsapp','quote_sent','booked','closed','completed','cancelled')),
  supplier_confirmed boolean default false, booking_ref varchar(100), submitted_by text, branch_id text,
  workflow_history jsonb, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
