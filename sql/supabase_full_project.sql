create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.branches (
  id text primary key default gen_random_uuid()::text,
  name varchar(100) not null,
  code varchar(10), phone varchar(20), email varchar(100), address text,
  license_no varchar(50), logo_url varchar(500),
  brand_color varchar(7) default '#7EC8E3', invoice_prefix varchar(10) default 'PGT',
  invoice_next integer default 1, default_roe numeric(10,2) default 78.00,
  settings jsonb, status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.users (
  id text primary key default gen_random_uuid()::text,
  username varchar(50) unique not null, password varchar(255) not null,
  full_name varchar(100) not null, email varchar(100), phone varchar(20), department varchar(50),
  role text not null default 'user' check (role in ('superadmin','admin','branch_admin','editor','viewer','user')),
  branch_id text references public.branches(id) on delete set null,
  status text not null default 'active' check (status in ('active','inactive')),
  permissions jsonb, last_login timestamptz,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.hotels (
  id text primary key default gen_random_uuid()::text,
  name varchar(200) not null, name_normalized varchar(200), city varchar(50) not null,
  country varchar(50) default 'Saudi Arabia', area varchar(100), distance_text varchar(100),
  distance_meters integer default 0, stars smallint default 0, shuttle boolean default false,
  status text not null default 'active' check (status in ('active','inactive')),
  description text, amenities text, image_url varchar(500), location_url varchar(1000),
  images jsonb, branch_visibility jsonb, dedup_key varchar(60), created_by text,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(), deleted_at timestamptz
);

create table if not exists public.hotel_vendors (
  id text primary key default gen_random_uuid()::text,
  hotel_id text not null references public.hotels(id) on delete cascade,
  vendor_name varchar(100) not null, room_type varchar(50) default 'DOUBLE', meal_plan varchar(20) default 'RO',
  price_all numeric(10,2) default 0, price_weekday numeric(10,2) default 0,
  price_weekend numeric(10,2) default 0, price_best numeric(10,2) default 0, extra_bed numeric(10,2) default 0,
  days_type text default 'ALL' check (days_type in ('ALL','WEEKDAY','WEEKEND','SPLIT')),
  checkin_date date, checkout_date date, remarks text,
  status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.vendors (
  id text primary key default gen_random_uuid()::text,
  name varchar(100) unique not null, phone varchar(20), email varchar(100), whatsapp varchar(20), address text,
  status text not null default 'active' check (status in ('active','inactive')),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.settings (
  id bigint generated by default as identity primary key,
  scope text not null default 'global' check (scope in ('global','branch')), branch_id text references public.branches(id) on delete cascade,
  company_name varchar(100), phone varchar(20), email varchar(100), address text, whatsapp varchar(20), license_no varchar(50), logo_url varchar(500),
  global_margin numeric(10,2) default 0, room_margins jsonb, default_roe numeric(10,2) default 78.00,
  default_visa_adult numeric(10,2) default 560, default_visa_child numeric(10,2) default 560, default_visa_infant numeric(10,2) default 150,
  invoice_prefix varchar(10) default 'PGT', invoice_next integer default 1, brand_color varchar(7) default '#7EC8E3',
  terms_text text, disclaimer_text text, filter_perms jsonb, tagline varchar(200), city_order varchar(20) default 'makkah_first',
  default_meal varchar(100) default 'BB', default_duration smallint default 15, session_timeout integer default 480,
  wa_quote_template text, wa_followup_template text, catalog_options jsonb,
  updated_at timestamptz not null default now()
);

create unique index if not exists uq_settings_scope_branch on public.settings(scope, coalesce(branch_id, ''));

